// process_status/lead_status/ops_status often includes free text a rep typed (a custom item
// label folded into lead_status like `לקוח נסגר ע"י דנה`) — translate the fixed prefix and leave
// the rest (names, custom labels) as-is rather than failing the whole lookup.
export function translateStatus(lang, text) {
  if (lang !== "en" || !text) return text;
  if (EN_TRANSLATIONS[text]) return EN_TRANSLATIONS[text];
  const prefix = 'לקוח נסגר ע"י ';
  if (text.startsWith(prefix)) return `${EN_TRANSLATIONS[prefix.trim()]} ${text.slice(prefix.length)}`;
  return text;
}

export function translate(lang, text) {
  if (lang !== "en" || text == null) return text;
  return EN_TRANSLATIONS[text] ?? text;
}
